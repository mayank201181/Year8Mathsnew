// Generates lib/generated/registry.ts: static imports for every topic, drill,
// extras and widget file that exists, in TOPIC_META order. Run before build
// (npm "prebuild") and after content changes.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const metaSrc = readFileSync(path.join(root, "lib/topics/meta.ts"), "utf8");
const ids = [...metaSrc.matchAll(/^\s{4}id: "([a-z0-9-]+)",$/gm)].map((m) => m[1]);
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const content = [
  "// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.",
  "// Server-side content registry (large): import only from server code.",
  'import type { Paper, TopicExtras, TopicGuide, TopicPractice } from "../types";',
  "",
];
const drillLines = [
  "// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.",
  "// Drill generators (small, client-safe).",
  'import type { Drill } from "../drills/types";',
  "",
];
const entries = [];
const drillEntries = [];
const missing = [];
for (const id of ids) {
  const c = camel(id);
  const has = (rel) => existsSync(path.join(root, rel));
  const e = { id };
  if (has(`lib/topics/${id}/guide.ts`)) { content.push(`import { guide as ${c}Guide } from "../topics/${id}/guide";`); e.guide = `${c}Guide`; } else missing.push(`${id}/guide`);
  if (has(`lib/topics/${id}/mcq.ts`)) { content.push(`import { mcqPapers as ${c}Mcq } from "../topics/${id}/mcq";`); e.mcq = `${c}Mcq`; } else missing.push(`${id}/mcq`);
  if (has(`lib/topics/${id}/practice.ts`)) { content.push(`import { practice as ${c}Practice } from "../topics/${id}/practice";`); e.practice = `${c}Practice`; } else missing.push(`${id}/practice`);
  if (has(`lib/topics/${id}/practice2.ts`)) { content.push(`import { morePapers as ${c}Practice2 } from "../topics/${id}/practice2";`); e.practice2 = `${c}Practice2`; } else missing.push(`${id}/practice2`);
  if (has(`lib/extras/${id}.ts`)) { content.push(`import { extras as ${c}Extras } from "../extras/${id}";`); e.extras = `${c}Extras`; } else missing.push(`extras/${id}`);
  if (has(`lib/drills/${id}.ts`)) { drillLines.push(`import { drills as ${c}Drills } from "../drills/${id}";`); drillEntries.push(`  ...${c}Drills,`); } else missing.push(`drills/${id}`);
  entries.push(e);
}
content.push(
  "",
  "export interface TopicFiles {",
  "  id: string;",
  "  guide?: TopicGuide;",
  "  mcqPapers: Paper[];",
  "  practice?: TopicPractice;",
  "  morePapers: Paper[];",
  "  extras: TopicExtras;",
  "}",
  "",
  "export const TOPIC_FILES: TopicFiles[] = [",
  ...entries.map((e) => `  { id: "${e.id}", guide: ${e.guide ?? "undefined"}, mcqPapers: ${e.mcq ?? "[]"}, practice: ${e.practice ?? "undefined"}, morePapers: ${e.practice2 ?? "[]"}, extras: ${e.extras ?? "{}"} },`),
  "];",
  "",
);
mkdirSync(path.join(root, "lib/generated"), { recursive: true });
writeFileSync(path.join(root, "lib/generated/content.ts"), content.join("\n"));
drillLines.push("", "export const ALL_DRILLS: Drill[] = [", ...drillEntries, "];", "");
writeFileSync(path.join(root, "lib/generated/drills.ts"), drillLines.join("\n"));

// Exam papers (server side).
const examIds = ["exam-n1", "exam-c1", "exam-n2", "exam-c2"];
const ex = ["// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.", 'import type { ExamPaper } from "../types";'];
const exNames = [];
for (const eid of examIds) {
  if (existsSync(path.join(root, `lib/exam/${eid}.ts`))) {
    const nm = camel(eid);
    ex.push(`import { paper as ${nm} } from "../exam/${eid}";`);
    exNames.push(nm);
  } else missing.push(`exam/${eid}`);
}
ex.push("", `export const EXAM_FILES: ExamPaper[] = [${exNames.join(", ")}];`, "");
writeFileSync(path.join(root, "lib/generated/exam.ts"), ex.join("\n"));

// Widgets registry (client side, lazy per topic).
const w = [
  "// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.",
  'import type { WidgetDef } from "./kit";',
  "",
  "export const WIDGET_LOADERS: Record<string, () => Promise<WidgetDef[]>> = {",
];
for (const id of ids) {
  if (existsSync(path.join(root, `components/widgets/${id}.tsx`))) w.push(`  "${id}": () => import("./${id}").then((m) => m.widgets),`);
  else missing.push(`widgets/${id}`);
}
w.push("};", "");
writeFileSync(path.join(root, "components/widgets/registry.ts"), w.join("\n"));
console.log(`registry: ${ids.length} topics; missing ${missing.length} files${missing.length ? ": " + missing.join(", ") : ""}`);
